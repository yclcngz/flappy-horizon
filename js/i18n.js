window.i18n = i18n;
window.currentLang = 'tr';

window.setLanguage = function(lang) {
    if (!i18n[lang]) return;
    window.currentLang = lang;
    localStorage.setItem('flappy_lang', lang);

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (i18n[lang][key]) {
            if (el.tagName === 'INPUT' && el.type === 'text') {
                el.placeholder = i18n[lang][key];
            } else {
                el.innerText = i18n[lang][key];
            }
        }
    });

    // Update Dropdowns
    const gradeSelect = document.getElementById('profileGrade');
    if (gradeSelect) {
        Array.from(gradeSelect.options).forEach(opt => {
            const val = opt.value;
            if (i18n[lang]['grade' + val]) {
                opt.innerText = i18n[lang]['grade' + val];
            }
        });
    }

    // Update level names dynamically
    if (window.levelManager) {
        const currentLevel = window.levelManager.getCurrentLevel();
        const levelKey = 'level' + currentLevel.id.charAt(0).toUpperCase() + currentLevel.id.slice(1);
        const translatedName = i18n[lang][levelKey] || currentLevel.name;
        
        const lblWorld = lang === 'en' ? 'World' : 'Dünya';
        const subtitleEl = document.getElementById('menuLevelSubtitle');
        if (subtitleEl) subtitleEl.innerText = `${lblWorld}: ${translatedName}`;
        
        const liveNameEl = document.getElementById('liveLevelName');
        if (liveNameEl) liveNameEl.innerText = translatedName;
    }

    // Trigger HUD update if game is running
    if (window.gameEngine && window.gameEngine.updateHUD) {
        window.gameEngine.updateHUD();
    }
    
    // Update placeholders
    const profileNameInput = document.getElementById('profileName');
    if (profileNameInput && i18n[lang].profileNameHolder) {
        profileNameInput.placeholder = i18n[lang].profileNameHolder;
    }
    
    const leaderNameInput = document.getElementById('playerNameInput');
    if (leaderNameInput && i18n[lang].namePlaceholder) {
        leaderNameInput.placeholder = i18n[lang].namePlaceholder;
    }
};

window.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('flappy_lang') || 'tr';
    window.setLanguage(savedLang);
});
